CREATE TABLE master_setting (
    key varchar PRIMARY KEY,
    value varchar,
    remarks varchar,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL
);

CREATE TABLE choice_master (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key varchar NOT NULL,
    no integer NOT NULL,
    value varchar NOT NULL,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL
);

CREATE TABLE group_setting_master (
    key varchar PRIMARY KEY,
    init_value varchar,
    remarks varchar,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL
);

CREATE TABLE user_setting_master (
    key varchar PRIMARY KEY,
    init_value varchar,
    remarks varchar,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL
);

CREATE TABLE notice (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar NOT NULL,
    content varchar NOT NULL,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL
);

CREATE TABLE "group" (
    group_id varchar PRIMARY KEY,
    group_password varchar NOT NULL,
    group_name varchar NOT NULL,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL
);

CREATE TABLE "user" (
    user_id varchar PRIMARY KEY,
    user_password varchar NOT NULL,
    user_name varchar NOT NULL,
    permission_flag integer,
    approve_flag integer,
    delete_flag integer,
    password_change_required integer NOT NULL DEFAULT 0,
    approve_date timestamp,
    delete_date timestamp,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL
);

CREATE TABLE group_member (
    group_id varchar NOT NULL,
    user_id varchar NOT NULL,
    approve_flag integer,
    leader_flag integer,
    approve_date timestamp,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    UNIQUE (group_id, user_id),
    FOREIGN KEY (group_id) REFERENCES "group"(group_id),
    FOREIGN KEY (user_id) REFERENCES "user"(user_id)
);

CREATE TABLE group_setting (
    group_id varchar NOT NULL,
    key varchar NOT NULL,
    value varchar,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id),
    FOREIGN KEY (key) REFERENCES group_setting_master(key)
);

CREATE TABLE user_setting (
    user_id varchar NOT NULL,
    key varchar NOT NULL,
    value varchar,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (user_id) REFERENCES "user"(user_id),
    FOREIGN KEY (key) REFERENCES user_setting_master(key)
);

CREATE TABLE category (
    id varchar PRIMARY KEY,
    group_id varchar NOT NULL,
    category_no integer,
    category_name varchar NOT NULL,
    disabled_flag integer,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id)
);

CREATE TABLE shopping_label (
    id varchar PRIMARY KEY,
    group_id varchar NOT NULL,
    label_no varchar,
    label_name varchar,
    disabled_flag integer,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id)
);

CREATE TABLE shopping (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id varchar NOT NULL,
    shopping_date timestamp,
    shopping_user_id varchar,
    category_id varchar,
    type integer,
    payment integer,
    settlement integer,
    amount integer,
    shopping_label_id varchar,
    remarks varchar,
    create_user_id varchar,
    fixed_flag integer,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id),
    FOREIGN KEY (shopping_user_id) REFERENCES "user"(user_id),
    FOREIGN KEY (category_id) REFERENCES category(id),
    FOREIGN KEY (create_user_id) REFERENCES "user"(user_id)
);

CREATE TABLE shopping_entry_list (
    id varchar PRIMARY KEY,
    group_id varchar NOT NULL,
    list_name varchar,
    shopping_user_id varchar,
    category_id varchar,
    type integer,
    payment integer,
    settlement integer,
    amount integer,
    shopping_label_ids varchar,
    remarks varchar,
    disabled_flag integer,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id),
    FOREIGN KEY (shopping_user_id) REFERENCES "user"(user_id),
    FOREIGN KEY (category_id) REFERENCES category(id),
    FOREIGN KEY (shopping_label_ids) REFERENCES shopping_label(id)
);

CREATE TABLE shopping_input_list (
    id varchar PRIMARY KEY,
    group_id varchar NOT NULL,
    list_name varchar,
    shopping_user_id varchar,
    category_id varchar,
    type integer,
    payment integer,
    settlement integer,
    amount integer,
    shopping_label_ids varchar,
    remarks varchar,
    disabled_flag integer,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id),
    FOREIGN KEY (shopping_user_id) REFERENCES "user"(user_id),
    FOREIGN KEY (category_id) REFERENCES category(id),
    FOREIGN KEY (shopping_label_ids) REFERENCES shopping_label(id)
);

CREATE TABLE shopping_search_list (
    id varchar PRIMARY KEY,
    group_id varchar NOT NULL,
    list_name varchar,
    from_shopping_date timestamp,
    to_shopping_date timestamp,
    shopping_user_id varchar,
    category_id varchar,
    type integer,
    payment integer,
    settlement integer,
    min_amount integer,
    max_amount integer,
    shopping_label_ids varchar,
    remarks varchar,
    create_user_id varchar,
    disabled_flag integer,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id),
    FOREIGN KEY (shopping_user_id) REFERENCES "user"(user_id),
    FOREIGN KEY (category_id) REFERENCES category(id),
    FOREIGN KEY (shopping_label_ids) REFERENCES shopping_label(id),
    FOREIGN KEY (create_user_id) REFERENCES "user"(user_id)
);

CREATE TABLE budgets (
    group_id varchar NOT NULL,
    year integer,
    month integer,
    category_id varchar,
    amount integer,
    fixed_flag integer,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id),
    FOREIGN KEY (category_id) REFERENCES category(id)
    ,UNIQUE (group_id, year, month, category_id)
);

CREATE TABLE fixed (
    group_id varchar NOT NULL,
    year integer,
    month integer,
    remarks varchar,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id)
    ,UNIQUE (group_id, year, month)
);

CREATE TABLE comment (
    id varchar PRIMARY KEY,
    group_id varchar NOT NULL,
    title varchar,
    content varchar,
    create_user_id varchar,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id),
    FOREIGN KEY (create_user_id) REFERENCES "user"(user_id)
);

CREATE TABLE communication (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id varchar NOT NULL,
    receive_date timestamp,
    receive_from varchar,
    receive_to varchar,
    receive_item varchar,
    receive_amount varchar,
    receive_remarks varchar,
    return_date timestamp,
    return_item varchar,
    return_amount varchar,
    return_remarks varchar,
    return_flag integer,
    create_date timestamp NOT NULL,
    update_date timestamp NOT NULL,
    FOREIGN KEY (group_id) REFERENCES "group"(group_id)
);


